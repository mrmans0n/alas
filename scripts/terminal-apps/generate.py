#!/usr/bin/env python3
"""Regenerate the terminal app catalog from catalog.tsv.

Writes the Swift entry table into AlasCore and one template imageset per
brand mark into the app's asset catalog. Brand marks and colours come from
Simple Icons (CC0). Fetch a copy first and pass its package directory:

    mkdir -p /tmp/simple-icons && cd /tmp/simple-icons && npm pack simple-icons && tar xzf simple-icons-*.tgz
    scripts/terminal-apps/generate.py /tmp/simple-icons/package
"""
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = ROOT / "scripts/terminal-apps/catalog.tsv"
EXTRA = ROOT / "scripts/terminal-apps/extra"
SWIFT = ROOT / "Packages/AlasCore/Sources/AlasAgentKit/Harness/TerminalAppCatalog+Entries.swift"
ASSETS = ROOT / "Alas/Resources/Assets.xcassets/AppLogos"
# Pure-black brands would vanish on dark themes; lift them to a dark grey.
DARK_FLOOR = "3A3A3C"


def luminance(hex_color):
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def swift_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(package):
    data = json.loads((package / "data/simple-icons.json").read_text())
    icons = data if isinstance(data, list) else data["icons"]
    colors = {}
    for icon in icons:
        slug = icon.get("slug") or re.sub(r"[^a-z0-9]", "", icon["title"].lower()
                                         .replace("+", "plus").replace(".", "dot").replace("&", "and"))
        colors[slug] = icon["hex"].upper()

    rows, seen_ids, seen_names = [], set(), {}
    # asset name -> (svg path, template rendering)
    assets = {}
    for line_number, line in enumerate(TABLE.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) not in (4, 5):
            sys.exit(f"{TABLE.name}:{line_number}: expected 4 or 5 tab-separated fields")
        app_id, name, names, glyph = fields[:4]
        tint = fields[4].upper() if len(fields) == 5 else None
        if app_id in seen_ids:
            sys.exit(f"{TABLE.name}:{line_number}: duplicate id {app_id}")
        seen_ids.add(app_id)
        processes = [n.strip().lower() for n in names.split(",") if n.strip()]
        for process in processes:
            if process in seen_names:
                sys.exit(f"{TABLE.name}:{line_number}: {process} already belongs to {seen_names[process]}")
            seen_names[process] = app_id
        kind, _, value = glyph.partition(":") if ":" in glyph else ("", "", glyph)
        if kind and not tint:
            sys.exit(f"{TABLE.name}:{line_number}: {kind} entries need a tint")
        if kind == "sf":
            swift_glyph = f".symbol({swift_string(value)})"
        elif kind in ("file", "logo"):
            source = EXTRA / f"{value}.svg"
            if not source.exists():
                sys.exit(f"{TABLE.name}:{line_number}: missing {source.relative_to(ROOT)}")
            asset = f"app-{value}"
            assets[asset] = (source, kind == "file")
            case = "brand" if kind == "file" else "logo"
            swift_glyph = f".{case}(assetName: {swift_string(asset)})"
        elif kind:
            sys.exit(f"{TABLE.name}:{line_number}: unknown glyph kind {kind}")
        else:
            if not (package / "icons" / f"{glyph}.svg").exists() or glyph not in colors:
                sys.exit(f"{TABLE.name}:{line_number}: Simple Icons has no {glyph}")
            assets[f"app-{glyph}"] = (package / "icons" / f"{glyph}.svg", True)
            swift_glyph = f".brand(assetName: {swift_string('app-' + glyph)})"
            tint = tint or colors[glyph]
            if luminance(tint) < 0.08:
                tint = DARK_FLOOR
        rows.append((processes, app_id, name, swift_glyph, tint))

    lines = [
        "// Generated by scripts/terminal-apps/generate.py from catalog.tsv. Do not edit.",
        "",
        "extension TerminalAppCatalog {",
        "    static let entries: [(names: [String], app: TerminalApp)] = [",
    ]
    for processes, app_id, name, glyph, tint in rows:
        names = ", ".join(swift_string(p) for p in processes)
        lines.append(f"        ([{names}], TerminalApp(id: {swift_string(app_id)}, displayName: {swift_string(name)}, "
                     f"glyph: {glyph}, tintHex: {swift_string(tint)})),")
    lines += ["    ]", "}", ""]
    SWIFT.write_text("\n".join(lines))

    if ASSETS.exists():
        shutil.rmtree(ASSETS)
    ASSETS.mkdir(parents=True)
    (ASSETS / "Contents.json").write_text(json.dumps(
        {"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": False}}, indent=2) + "\n")
    for asset, (source, template) in sorted(assets.items()):
        imageset = ASSETS / f"{asset}.imageset"
        imageset.mkdir()
        (imageset / f"{asset}.svg").write_text(re.sub(r"<title>.*?</title>", "", source.read_text()))
        properties = {"preserves-vector-representation": True}
        if template:
            properties["template-rendering-intent"] = "template"
        (imageset / "Contents.json").write_text(json.dumps({
            "images": [{"idiom": "universal", "filename": f"{asset}.svg"}],
            "info": {"author": "xcode", "version": 1},
            "properties": properties,
        }, indent=2) + "\n")
    print(f"{len(rows)} apps, {len(seen_names)} process names, {len(assets)} logos")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(pathlib.Path(sys.argv[1]))
