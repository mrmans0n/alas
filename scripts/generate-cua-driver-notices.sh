#!/usr/bin/env bash
# Regenerates ThirdParty/cua-driver/THIRD-PARTY-NOTICES.txt: the licences of
# every crate the bundled Cua Driver links, for its aarch64 glibc Linux build at
# the commit scripts/fetch-cua-driver.sh pins. Run it again whenever that pin
# moves. Needs network, git and cargo-about
# (`cargo install cargo-about --locked --features cli`).
#
# The checkout is only read: no build scripts or scripts of its own run. Cargo
# runs from outside it, so its rust-toolchain.toml and .cargo config don't apply.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
srcroot="$(cd "${script_dir}/.." && pwd)"
config_dir="${script_dir}/cua-driver-notices"
output="${srcroot}/ThirdParty/cua-driver/THIRD-PARTY-NOTICES.txt"
target="aarch64-unknown-linux-gnu"

source_commit="$(sed -n 's/^source_commit="\([0-9a-f]*\)"$/\1/p' "${script_dir}/fetch-cua-driver.sh")"
[ -n "${source_commit}" ] || { echo "generate-cua-driver-notices.sh: no source_commit in fetch-cua-driver.sh" >&2; exit 1; }
command -v cargo-about >/dev/null || { echo "generate-cua-driver-notices.sh: cargo-about is not installed" >&2; exit 1; }

work_dir="$(mktemp -d)"
trap 'rm -rf "${work_dir}"' EXIT
checkout="${work_dir}/cua"
git clone --quiet --filter=blob:none --no-checkout --sparse https://github.com/trycua/cua.git "${checkout}"
git -C "${checkout}" sparse-checkout set libs/cua-driver/rust libs/cua/crates/cua-telemetry
git -C "${checkout}" checkout --quiet "${source_commit}"

manifest="${checkout}/libs/cua-driver/rust/crates/cua-driver/Cargo.toml"
mkdir -p "${work_dir}/run"
cd "${work_dir}/run"
cargo fetch --locked --manifest-path "${manifest}" --target "${target}"
cargo about generate --locked --offline --fail \
    -c "${config_dir}/about.toml" -m "${manifest}" \
    -o "${work_dir}/notices.txt" "${config_dir}/notices.hbs"

mkdir -p "$(dirname "${output}")"
{
    echo "Third-party notices for Cua Driver (https://github.com/trycua/cua)"
    echo
    echo "Cua Driver, built from trycua/cua commit ${source_commit}"
    echo "(libs/cua-driver/rust, crate cua-driver, target ${target}), links the crates"
    echo "below under the licences shown. Generated by"
    echo "scripts/generate-cua-driver-notices.sh with $(cargo about --version), from the"
    echo "crate's Cargo.lock, without build and dev dependencies. Do not edit by hand."
    echo
    # Some licence files have CRLF line ends; git would rewrite them anyway.
    tr -d '\r' < "${work_dir}/notices.txt"
} > "${output}"
echo "generate-cua-driver-notices.sh: wrote ${output}"
