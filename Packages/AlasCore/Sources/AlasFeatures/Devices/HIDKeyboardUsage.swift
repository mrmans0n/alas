/// USB HID keyboard usages (page 0x07) for Mac virtual key codes (Carbon's
/// `kVK_*`). Both name a physical key position, so the simulator's own
/// keyboard layout decides which character a key types.
public enum HIDKeyboardUsage {
    public static func usage(forKeyCode keyCode: UInt16) -> UInt32? {
        keys[keyCode]
    }

    /// Shift, Control and Option. Command is left to Alas so its shortcuts keep working.
    public static func usage(forModifierKeyCode keyCode: UInt16) -> UInt32? {
        modifiers[keyCode]
    }

    private static let keys: [UInt16: UInt32] = [
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, // A B C D E F
        0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, // G H I J K L
        0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15, // M N O P Q R
        0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B, // S T U V W X
        0x10: 0x1C, 0x06: 0x1D,                                                 // Y Z
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22,             // 1 2 3 4 5
        0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,             // 6 7 8 9 0
        0x24: 0x28, // Return
        0x35: 0x29, // Escape
        0x33: 0x2A, // Delete (backspace)
        0x30: 0x2B, // Tab
        0x31: 0x2C, // Space
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31,             // - = [ ] \
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38, // ; ' ` , . /
        0x75: 0x4C, // Forward delete
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52, // Right, left, down, up arrows
        0x4C: 0x58, // Keypad Enter
    ]

    private static let modifiers: [UInt16: UInt32] = [
        0x3B: 0xE0, 0x38: 0xE1, 0x3A: 0xE2, // Left Control, Shift, Option
        0x3E: 0xE4, 0x3C: 0xE5, 0x3D: 0xE6, // Right Control, Shift, Option
    ]
}
